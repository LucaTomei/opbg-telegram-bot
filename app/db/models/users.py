"""Telegram users, invites and redemptions."""

from __future__ import annotations

import uuid
from datetime import datetime, time
from typing import TYPE_CHECKING

from sqlalchemy import (
    BINARY,
    BigInteger,
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Time,
    UniqueConstraint,
)
from sqlalchemy import (
    Enum as SAEnum,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import (
    Base,
    SoftDeleteMixin,
    TimestampMixin,
    UuidPkMixin,
    VersionMixin,
    encrypted_text,
)
from app.db.types import Ciphertext, UuidBinary
from app.domain.enums import PdfDeliveryMode, UserRole, UserStatus

if TYPE_CHECKING:
    from app.db.models.accounts import PortalAccount


class TelegramUser(UuidPkMixin, TimestampMixin, VersionMixin, SoftDeleteMixin, Base):
    """A Telegram user allowed to use the bot."""

    __tablename__ = "telegram_users"

    telegram_id: Mapped[int] = mapped_column(BigInteger, unique=True, nullable=False, index=True)
    username_ciphertext: Mapped[bytes | None] = mapped_column(Ciphertext(512), default=None)
    first_name_ciphertext: Mapped[bytes | None] = mapped_column(Ciphertext(512), default=None)
    last_name_ciphertext: Mapped[bytes | None] = mapped_column(Ciphertext(512), default=None)
    role: Mapped[UserRole] = mapped_column(
        SAEnum(UserRole, native_enum=False, length=16), default=UserRole.USER, nullable=False
    )
    status: Mapped[UserStatus] = mapped_column(
        SAEnum(UserStatus, native_enum=False, length=24),
        default=UserStatus.PENDING_CONSENT,
        nullable=False,
        index=True,
    )
    timezone: Mapped[str] = mapped_column(String(64), default="Europe/Rome", nullable=False)
    notifications_enabled: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    quiet_hours_start: Mapped[time | None] = mapped_column(Time, default=None)
    quiet_hours_end: Mapped[time | None] = mapped_column(Time, default=None)
    pdf_delivery_mode: Mapped[PdfDeliveryMode] = mapped_column(
        SAEnum(PdfDeliveryMode, native_enum=False, length=24),
        default=PdfDeliveryMode.TELEGRAM,
        nullable=False,
    )
    page_size: Mapped[int] = mapped_column(Integer, default=6, nullable=False)
    max_slots_shown: Mapped[int] = mapped_column(Integer, default=40, nullable=False)
    consent_version: Mapped[str | None] = mapped_column(String(16), default=None)
    consented_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)

    username = encrypted_text("username_ciphertext")
    first_name = encrypted_text("first_name_ciphertext")
    last_name = encrypted_text("last_name_ciphertext")

    portal_accounts: Mapped[list[PortalAccount]] = relationship(
        back_populates="user", lazy="noload"
    )

    @property
    def is_admin(self) -> bool:
        return self.role is UserRole.ADMIN

    @property
    def can_use_portal(self) -> bool:
        return self.status is UserStatus.ACTIVE and self.deleted_at is None

    @property
    def has_consented(self) -> bool:
        return self.consented_at is not None and self.consent_version is not None


class InviteCode(UuidPkMixin, TimestampMixin, Base):
    """A single-use or multi-use invite generated by an administrator."""

    __tablename__ = "invite_codes"

    code_hash: Mapped[bytes] = mapped_column(BINARY(32), unique=True, nullable=False)
    created_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UuidBinary, ForeignKey("telegram_users.id", ondelete="RESTRICT"), nullable=False
    )
    expires_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    max_uses: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    used_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)
    note: Mapped[str | None] = mapped_column(String(255), default=None)

    def is_usable(self, now: datetime) -> bool:
        return self.revoked_at is None and self.expires_at > now and self.used_count < self.max_uses


class InviteRedemption(UuidPkMixin, TimestampMixin, Base):
    """Records which user consumed which invite."""

    __tablename__ = "invite_redemptions"
    __table_args__ = (UniqueConstraint("invite_id", "telegram_user_id"),)

    invite_id: Mapped[uuid.UUID] = mapped_column(
        UuidBinary, ForeignKey("invite_codes.id", ondelete="CASCADE"), nullable=False
    )
    telegram_user_id: Mapped[uuid.UUID] = mapped_column(
        UuidBinary, ForeignKey("telegram_users.id", ondelete="CASCADE"), nullable=False
    )
    redeemed_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)


class UserSettingsAudit(UuidPkMixin, TimestampMixin, Base):
    """Non-sensitive trail of user driven settings changes."""

    __tablename__ = "user_settings_audit"

    telegram_user_id: Mapped[uuid.UUID] = mapped_column(
        UuidBinary, ForeignKey("telegram_users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    setting: Mapped[str] = mapped_column(String(64), nullable=False)
    old_value: Mapped[str | None] = mapped_column(String(128), default=None)
    new_value: Mapped[str | None] = mapped_column(String(128), default=None)
